/*
 * HOTLINE ABAKAN — сцена для витрины.
 *
 * Карточка игры на сайте показывает не снимок, а короткую петлю с самым
 * ярким моментом. Готовое видео отсюда не отдаётся: игра даёт снаряд —
 * вызов, который ставит сцену и играет её, — а снимает витрина. Так никто
 * не лезет в чужое дерево, и петля всегда соответствует нынешней игре, а
 * не тому, как она выглядела в день записи.
 *
 * Момент выбран такой, какого нет ни у кого: удар в долю музыки. В долю
 * безоружный падает с одного касания вместо двух, дуга светится кислотным
 * вместо белого, а над телом всплывает счёт.
 *
 * Сцена детерминирована целиком — свой этаж, свои позиции, свои доли,
 * свой сценарий нажатий. Одна и та же петля у всех, кто её снимет.
 */

import { fromAscii } from './level.js';
import { BEAT_PERIOD } from './world.js';

/*
 * Комната нарочно больше кадра: пока этаж меньше экрана, камера
 * показывает его целиком и держит игрока там, где он есть, — в углу. А в
 * трёхсекундной петле действие должно быть в середине.
 */
const ROOM = [
  '##############################',
  '#............................#',
  '#.....==....k.......==.......#',
  '#............................#',
  '#............................#',
  '#....@.........k.............#',
  '#............................#',
  '#.....==............==.......#',
  '#............................#',
  '#............................#',
  '#............................#',
  '#............................#',
  '#............................#',
  '##############################',
];

export const SHOWCASE_SECONDS = 3;

export function showcaseLevel() {
  const level = fromAscii(ROOM, { theme: 0, track: 0 });
  level.title = 'HOTLINE ABAKAN';
  level.call = '';
  return level;
}

/*
 * Расстановка. Двое по очереди: цепочка успевает вырасти до ×2, и над
 * вторым всплывает уже +200. Третий в три секунды не влезает — удары
 * ложатся только на доли, а доля здесь раз в 0.56 секунды.
 *
 * Расстояния подобраны по доле: первый падает на второй доле, второй — на
 * четвёртой. Удары ложатся ровно в такт, и это видно даже без звука — по
 * кольцу, которое сжимается вокруг игрока.
 */
export function stageShowcase(world) {
  const player = world.player;
  player.weapon = 'fists';
  player.angle = 0;
  player.vx = 0;
  player.vy = 0;

  const crowd = world.enemies.filter((e) => e.alive).slice(0, 2);
  crowd.forEach((enemy, i) => {
    enemy.x = player.x + [120, 190][i];
    enemy.y = player.y + [0, -22][i];
    enemy.angle = Math.PI;
    enemy.vx = 0;
    enemy.vy = 0;
    enemy.state = 'idle';
    enemy.cooldown = 99;          /* бьём мы, а не нас: это витрина */
  });
  for (const enemy of world.enemies) if (!crowd.includes(enemy)) enemy.alive = false;

  /* Доли ставятся вручную: удар должен попасть в них наверняка. */
  world.beatAt = world.time - BEAT_PERIOD * 0.5;
  return crowd;
}

/*
 * Сценарий нажатий по времени сцены. Возвращает намерение — то же самое,
 * что обычно приходит от рук игрока, поэтому дальше работает вся игра:
 * наводка, откат, ритм, кровь.
 */
export function showcaseIntent(t, world) {
  const target = world.enemies.find((e) => e.alive);
  const angle = target
    ? Math.atan2(target.y - world.player.y, target.x - world.player.x)
    : 0;
  const dist = target
    ? Math.hypot(target.x - world.player.x, target.y - world.player.y)
    : 0;

  const close = dist < 26;
  const beat = ((t + BEAT_PERIOD * 0.5) % BEAT_PERIOD) < 1 / 30;

  /*
   * Идём вполсилы: на полной скорости двое кончаются за секунду, и петля
   * превращается в мельтешение. Здесь важно, чтобы глаз успел прочитать
   * каждый удар.
   */
  return {
    moveX: close ? 0 : Math.cos(angle) * 0.5,
    moveY: close ? 0 : Math.sin(angle) * 0.5,
    aimAngle: angle,
    attack: close && beat,
    pickup: false,
    throw: false,
  };
}
