/*
 * Выход из игры на сайт.
 *
 * Правило владельца: кнопка «НА САЙТ» должна быть видна всегда, а не
 * только между попытками, — и если партия идёт, нажатие обязано
 * спросить, назвав цену словами.
 *
 * Раньше эта кнопка на телефоне пряталась во время боя: случайное
 * касание стоило партии, и я убрал кнопку вместо того, чтобы убрать
 * последствие. Вопрос решает ту же задачу, ничего не отнимая: палец
 * промахнулся — ответил «нет» и вернулся в бой.
 *
 * Правило вынесено сюда отдельным файлом, потому что main.js трогает
 * документ и в прогон не импортируется. Всё, что живёт только там,
 * проверками не покрыто вовсе.
 */

export const EXIT_URL = 'https://aka-gst.ru/#games';

/*
 * Цена названа словами, а не подразумевается. «Точно выйти?» без
 * продолжения человек читает как «закрыть окно» и жмёт да.
 */
export const EXIT_QUESTION =
  'Точно выйти на сайт? Партия прервётся, и прогресс может не сохраниться.';

/*
 * Спрашиваем там, где есть что терять: в бою и в паузе. На заставке
 * терять нечего, а после гибели попытка уже кончилась — лишний вопрос
 * там раздражает и приучает жать «да» не глядя, то есть обесценивает
 * вопрос в бою.
 */
export function needsConfirm(scene) {
  return scene === 'play' || scene === 'pause';
}
