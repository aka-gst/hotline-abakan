const assert=require('assert');
const core=require('../Game/src/core.js');
const {TUNING:T,ATTACKS,ENEMY_WEAPONS,GATES,ENCOUNTERS,CHAPTERS,makeRunState,pipeCanPickup,chapterForZ,segmentBlocked,stylePoints,gradeRun}=core;

assert(T.playerSpeed>=5.0 && T.playerSpeed<=5.7,'movement stays fast/readable');
assert(T.dodgeDuration>=.30 && T.dodgeDuration<=.36,'dodge remains a readable evasive step');
assert(T.dodgeSpeed<=7.5,'dodge cannot blink across a room');
assert(T.sneakSpeed<T.playerSpeed*.6,'quiet movement is deliberately slower than normal movement');
assert(T.sneakFootstepNoise<T.footstepNoise*.35,'quiet steps have a much smaller hearing radius');
assert(T.hearQuietDoor<T.hearDoor*.4,'controlled door opening is meaningfully quieter than a bash');
assert(T.stealthRange<=1.15,'stealth takedown requires intimate positioning');
assert(T.pipeThrowSpeed>=10 && T.pipeThrowSpeed<=14,'pipe throw is fast but trackable');
assert(T.enemyAlertRadius>=5.5 && T.enemyAlertRadius<=7.5,'final-room alert propagation is local, not global');
assert(T.styleWindow>=2.2 && T.styleWindow<=3.0,'style chain gives time to improvise without becoming permanent');
assert(T.extractionRange<=1.5,'extraction remains a physical location, not a global completion trigger');
assert(T.enemyFov<Math.PI,'idle enemies retain a forward FOV');
assert(T.hearDoor>T.hearAttack,'doors are louder than fists');
assert(ATTACKS.fists.heavy.knockdown===true,'fist heavy can knock down');
assert(ATTACKS.pipe.heavy.knockdown===true,'pipe changes the moveset');
assert(ENEMY_WEAPONS.pipe.windup>ENEMY_WEAPONS.fists.windup,'enemy pipe has distinct timing');
assert.strictEqual(ENCOUNTERS.length,7,'six scenes culminate in a two-enemy final room');
assert.strictEqual(GATES.length,6,'six progression gates');
assert.strictEqual(ENCOUNTERS.filter(e=>e.finalPair).length,2,'final room owns exactly two authored enemies');
const behaviors=new Set(ENCOUNTERS.map(e=>e.behavior));
for(const b of ['sentry','patrol','brute','opportunist','flanker'])assert(behaviors.has(b),`missing ${b} archetype`);
assert(ENCOUNTERS.filter(e=>e.behavior==='patrol').every(e=>e.patrol),'patrol archetypes own patrol data');
assert(CHAPTERS.length>=8,'level remains chunked into beats');
assert(CHAPTERS.at(-1).title.includes('ОБРАТНЫЙ'),'last beat is extraction/backtrack, not an instant score screen');

const blocked=segmentBlocked({x:0,z:0},{x:4,z:0},[{minX:1.8,maxX:2.2,minZ:-1,maxZ:1,blocksVision:true}]);
assert(blocked,'world geometry blocks sight');

const s=makeRunState();
assert.strictEqual(s.phase,'intro');
assert.strictEqual(s.player.weapon,'fists');
assert.strictEqual(s.mission.cassetteTaken,false,'mission objective begins in world');
assert.strictEqual(s.mission.extractReady,false,'extraction is earned only after the climax');
assert.strictEqual(s.pipe.owner,null);
assert.strictEqual(s.pipe.thrown,false);
assert.strictEqual(s.score,0);
assert.strictEqual(s.styleMult,1);
assert.strictEqual(s.peakStyle,1);
assert.strictEqual(s.throws,0);
assert.strictEqual(s.stealthKills,0);
assert(s.enemies.every(e=>e.behavior),'enemy behavior belongs to simulation state');
assert(!pipeCanPickup(s.player,s.pipe),'pipe cannot be picked up from spawn');
assert(stylePoints('throw')>stylePoints('quick'),'improvisation beats button spam');
assert(stylePoints('stealth')>stylePoints('quick'),'stealth approach is rewarded as a distinct solution');
assert(stylePoints('break')>stylePoints('quick'),'using the room is rewarded more than another jab');
assert(stylePoints('objective')>stylePoints('kill'),'mission goal matters more than one kill');
assert(['S','A','B','C','D'].includes(gradeRun(8000,6,70)),'grade function returns a real grade');
assert.strictEqual(chapterForZ(8.5,0),0);
assert.strictEqual(chapterForZ(-31,6),6,'one final-room enemy down does not finish the level');
assert.strictEqual(chapterForZ(-10,7),7,'only both final enemies down enters extraction beat');
console.log('slice-core-12: OK');
